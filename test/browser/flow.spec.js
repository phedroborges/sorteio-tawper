import { test, expect } from '@playwright/test';
test('celular → cadastro → tabela → edição → CSV → sorteio real de 10 segundos', async ({ page, request }) => {
  const failures = [];
  page.on('pageerror', error => failures.push(error.message));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.getByLabel('Nome completo')).toBeVisible();
  await expect(page.locator('a[href*="admin"]')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/cadastro-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Confirmar participação' }).click();
  await expect(page.locator('#name-error')).not.toBeEmpty();
  await page.getByLabel('Nome completo').fill('Ana Participante');
  await page.getByLabel('Telefone com DDD').fill('11987654321');
  await expect(page.getByLabel('Telefone com DDD')).toHaveValue('(11) 98765-4321');
  await page.getByLabel('Cargo', { exact: true }).fill('Engenheira');
  await page.getByLabel('Empresa que representa').fill('Usina Exemplo');
  await page.locator('#consent').check();
  await page.getByRole('button', { name: 'Confirmar participação' }).click();
  await expect(page.locator('#success-view')).toBeVisible();
  await expect(page.locator('#ticket-number')).toContainText('0001');
  // Additional synthetic participants only in this isolated, in-memory test server.
  for (const [name, phone] of [['Bruno Participante', '11987654322'], ['Carla Participante', '11987654323']]) {
    const response = await request.post('/api/registrations', { headers: { 'X-Tawper-Request': '1' }, data: { name, phone, role: 'Gestor', company: 'Empresa Exemplo', consent: true } });
    expect(response.status()).toBe(201);
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');
  await page.screenshot({ path: 'artifacts/cadastro-desktop.png', fullPage: true });
  await page.goto('/admin');
  await expect(page.locator('#stat-total')).toHaveText('3');
  await page.screenshot({ path: 'artifacts/admin-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Editar Ana Participante', exact: true }).click();
  await page.getByLabel('Empresa', { exact: true }).fill('Usina Atualizada');
  await page.getByRole('button', { name: 'Salvar alterações' }).click();
  await expect(page.locator('#participants-body')).toContainText('Usina Atualizada');
  await page.getByRole('searchbox').fill('Ana');
  await expect(page.locator('#participants-body tr')).toHaveCount(1);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Exportar CSV' }).click();
  expect((await downloadPromise).suggestedFilename()).toMatch(/tawper-participantes/);
  await page.getByRole('button', { name: 'Sorteio', exact: true }).click();
  await page.getByRole('button', { name: 'Iniciar sorteio' }).click();
  const started = Date.now();
  await page.getByRole('button', { name: 'Começar os 10 segundos' }).click();
  await expect(page.locator('#draw-stage')).toBeVisible();
  await expect(page.locator('#countdown')).toBeVisible();
  await page.screenshot({ path: 'artifacts/sorteio-contagem.png' });
  await page.reload();
  await expect(page.locator('#draw-stage')).toBeVisible();
  await expect(page.locator('#countdown')).toBeVisible();
  await expect(page.locator('#winner-content')).toBeVisible({ timeout: 16000 });
  expect(Date.now() - started).toBeGreaterThanOrEqual(9900);
  const winner = await page.locator('#winner-name').textContent();
  expect(['Ana Participante', 'Bruno Participante', 'Carla Participante']).toContain(winner);
  await page.locator('#winner-content').evaluate(el => Promise.all(el.getAnimations().map(animation => animation.finished)));
  await page.getByRole('button', { name: 'Tela cheia' }).click();
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(true);
  await expect(page.locator('#winner-name')).toBeVisible();
  await page.getByRole('button', { name: 'Tela cheia' }).click();
  await page.screenshot({ path: 'artifacts/sorteio-resultado.png' });
  await page.getByRole('button', { name: 'Voltar ao painel ↗' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Histórico', exact: true }).click();
  await expect(page.locator('#history-list')).toContainText(winner);
  await expect(page.locator('#stat-eligible')).toHaveText('2');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Participantes', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/admin-mobile.png', fullPage: true });
  await page.getByRole('button', { name: /Inscrições abertas/ }).click();
  await page.locator('#confirm-action').click();
  await page.goto('/');
  await expect(page.locator('#closed-view')).toBeVisible();
  await page.goto('/admin');
  await page.getByRole('button', { name: /Inscrições encerradas/ }).click();
  await page.locator('#confirm-action').click();
  await expect(page.locator('#registration-toggle')).toContainText('Inscrições abertas');
  await page.getByRole('button', { name: 'Excluir Ana Participante', exact: true }).click();
  await page.getByRole('button', { name: 'Excluir cadastro', exact: true }).click();
  await expect(page.locator('#stat-total')).toHaveText('2');
  expect(failures).toEqual([]);
});
